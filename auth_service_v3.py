"""Authentication service — multi-user support, dynamic registration codes, audit logging.

Security model:
- Users stored in JSON file on disk (data/auth/users.json)
- Registration codes generated by admin, stored in data/auth/registration_codes.json
- Codes support max_uses and optional expiry
- Passwords hashed with PBKDF2-HMAC-SHA256 (100k iterations)
- Session tokens cryptographically random, in-memory with expiry
- All auth events recorded in audit log (JSONL persisted to disk)
"""
